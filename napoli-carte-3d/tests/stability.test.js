'use strict';
const assert=require('node:assert/strict'),e=require('../backend/engine.js'),live=require('../backend/realtime.js');
assert.equal(typeof e.housekeeping,'function');
assert.equal(typeof e.lookupSession,'function');
const a=e.join({game:'scopa',seats:2,name:'Test A',private:true});
const b=e.join({game:'scopa',seats:2,name:'Test B',invite:a.code});
let r=e.rooms.get(a.roomId);
assert.equal(e.state(a.token).status,'playing');
assert.equal(e.lookupSession(a.token).seat,0);
const prev=r.updated;
r.updated=Date.now()-1000*60*30;
assert.equal(e.housekeeping().removed,0);
assert.equal(e.state(a.token).roomId,a.roomId);
const before=e.state(b.token).players;
e.leave(a.token);
assert.equal(e.lookupSession(a.token),null);
assert.equal(e.state(b.token).players[0].bot,true);
assert.equal(e.state(b.token).roomId,a.roomId);
r.updated=Date.now()-5*60*60*1000;
assert(e.housekeeping().removed>=1);
assert.equal(e.lookupSession(b.token),null);
const waiting=e.join({game:'briscola',seats:2,name:'Waiting',private:true});
const wr=e.rooms.get(waiting.roomId);wr.updated=Date.now()-60*60*1000;
