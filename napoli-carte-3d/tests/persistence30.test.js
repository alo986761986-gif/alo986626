'use strict';
const assert=require('node:assert/strict'),engine=require('../backend/engine');
const a=engine.join({game:'scopa',seats:2,name:'Giocatore A',private:true});
const b=engine.join({game:'scopa',seats:2,name:'Giocatore B',invite:a.code});
const state=engine.state(a.token);
assert.equal(state.status,'playing');
const r=engine.rooms.get(a.roomId);
r.players[0].photo='data:image/jpeg;base64,NOT_SAVED';
r.players[0].photoMode='public';
const snap=engine.exportSnapshot();
assert.equal(snap.version,1);
assert.equal(snap.rooms.find(v=>v.id===a.roomId).players[0].photo,null);
const serialized=JSON.parse(JSON.stringify(snap));
const restored=engine.importSnapshot(serialized);
assert(restored.rooms>=1);
assert.equal(engine.state(a.token).roomId,a.roomId);
assert.equal(engine.state(b.token).status,'playing');
assert.equal(engine.state(a.token).players[0].photo,null);
assert.equal(engine.rooms.get(a.roomId).players[0].photoMode,'avatar');
assert.equal(engine.rooms.get(a.roomId).players[0].hand.length,r.players[0].hand.length);
assert.equal(engine.lookupSession(b.token).seat,1);
const firstHand=engine.state(a.token).hand[0];
const move=engine.opts(a.token,firstHand.id).options[0];
const result=engine.action(a.token,{card:firstHand.id,...move});
assert.equal(result.turn,1);
const after=engine.exportSnapshot();
engine.importSnapshot(JSON.parse(JSON.stringify(after)));
assert.equal(engine.state(b.token).turn,1);
assert.throws(()=>engine.importSnapshot({version:999,rooms:[]}),/versione non valida/);
console.log('PERSISTENCE ROUNDTRIP PASS: 2 player tokens, turn, private photo stripping, move state');
